"""'Explain Song' via the Gemini REST API.

Uses httpx (already a dependency of python-telegram-bot) instead of the
google-genai SDK, which pulled in 18 extra packages (~30 MB of layer).
"""

import html
import logging
import os

import httpx

logger = logging.getLogger()

MODEL = os.getenv("GEMINI_MODEL", "gemini-3.5-flash-lite")
# Optional: "low" / "medium" / "high" (Gemini 3 models think by default; the
# Flash-Lite default is "minimal", the Flash default is "medium"). Leave empty
# to use the model's default.
THINKING_LEVEL = os.getenv("GEMINI_THINKING_LEVEL", "")
API_KEY = os.getenv("GEMINI_API_KEY", "")
TIMEOUT_SECONDS = float(os.getenv("GEMINI_TIMEOUT_SECONDS", "20"))
ENDPOINT = "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"

disclaimer = "\n\n<i>Generated by AI (Google Gemini 3.5)</i>"
error_message = "<i>This feature is temporarily unavailable</i>"

PROMPT = (
    "Explain this hymn in up to 7 lines. "
    "Reply in plain text only: no Markdown, no asterisks, no headings."
)

_client = None


def _http():
    # One connection pool per warm container (created on first use, so a
    # missing key or network problem can only ever affect this feature).
    global _client
    if _client is None:
        _client = httpx.Client(timeout=TIMEOUT_SECONDS)
    return _client


def _generate(lyrics):
    body = {"contents": [{"role": "user", "parts": [{"text": PROMPT}, {"text": lyrics}]}]}
    if THINKING_LEVEL:
        body["generationConfig"] = {"thinkingConfig": {"thinkingLevel": THINKING_LEVEL}}
    response = _http().post(
        ENDPOINT.format(model=MODEL), headers={"x-goog-api-key": API_KEY}, json=body
    )
    response.raise_for_status()
    data = response.json()
    usage = data.get("usageMetadata", {})
    logger.info(
        "gemini model=%s prompt_tokens=%s output_tokens=%s thought_tokens=%s",
        MODEL, usage.get("promptTokenCount"), usage.get("candidatesTokenCount"),
        usage.get("thoughtsTokenCount"),
    )
    candidates = data.get("candidates") or []
    if not candidates:
        # Typically promptFeedback.blockReason (safety filter); treat as unavailable.
        raise ValueError(f"no candidates: {data.get('promptFeedback')}")
    parts = candidates[0].get("content", {}).get("parts", [])
    text = "".join(p.get("text", "") for p in parts).strip()
    if not text:
        raise ValueError(f"empty answer, finishReason={candidates[0].get('finishReason')}")
    return text


def explainSong(lyrics):
    if not API_KEY:
        logger.warning("explainSong called without GEMINI_API_KEY")
        return error_message
    try:
        text = _generate(lyrics)
    except Exception:
        logger.exception("explainSong failed")
        return error_message
    # Model output is untrusted for Telegram HTML parse mode.
    return html.escape(text) + disclaimer
